import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryColumn,
  UpdateDateColumn,
} from 'typeorm';

/**
 * ------------------------------------------------------------------------
 * Conversation ORM Entity
 * ------------------------------------------------------------------------
 *
 * Stores conversation ownership and lifecycle information.
 *
 * Conversation messages, state, and product references
 * are persisted separately in their respective repositories.
 * ------------------------------------------------------------------------
 */
@Entity({
  name: 'support_chat_conversations',
})
@Index('IDX_support_chat_conversations_owner', ['ownerType', 'ownerId'])
@Index('IDX_support_chat_conversations_status_expiration', [
  'status',
  'expiresAt',
])
export class ConversationOrmEntity {
  /**
   * Unique conversation identifier generated by the application.
   */
  @PrimaryColumn({
    type: 'uuid',
  })
  id: string;

  /**
   * Type of the conversation owner.
   *
   * guest = Guest identity
   * user = Authenticated application user
   */
  @Column({
    name: 'owner_type',
    type: 'varchar',
    length: 10,
  })
  ownerType: 'guest' | 'user';

  /**
   * Internal identifier of the conversation owner.
   */
  @Column({
    name: 'owner_id',
    type: 'uuid',
  })
  ownerId: string;

  /**
   * Current conversation lifecycle status.
   */
  @Column({
    type: 'varchar',
    length: 10,
    default: 'active',
  })
  status: 'active' | 'closed';

  /**
   * Conversation creation timestamp.
   */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamptz',
  })
  createdAt: Date;

  /**
   * Last conversation update timestamp.
   */
  @UpdateDateColumn({
    name: 'updated_at',
    type: 'timestamptz',
  })
  updatedAt: Date;

  /**
   * Conversation expiration timestamp.
   */
  @Column({
    name: 'expires_at',
    type: 'timestamptz',
  })
  expiresAt: Date;
}
