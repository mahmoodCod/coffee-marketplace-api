import {
  BadRequestException,
  Injectable,
  InternalServerErrorException,
  Logger,
  NotFoundException,
  RequestTimeoutException,
} from '@nestjs/common';
import Ajv, { type ValidateFunction } from 'ajv';
import { ToolRegistryService } from './tool-registry.service';

@Injectable()
export class ToolExecutorService {
  private readonly logger = new Logger(ToolExecutorService.name);

  // Maximum execution time allowed for a support tool.
  private readonly TOOL_EXECUTION_TIMEOUT_MS = 15_000;

  // Maximum serialized output size allowed for a support tool.
  private readonly MAX_TOOL_OUTPUT_BYTES = 32 * 1024;

  private readonly ajv = new Ajv({
    allErrors: true,
    strict: true,
    coerceTypes: false,
    removeAdditional: false,
    useDefaults: false,
  });

  // Cache compiled validators to avoid compiling the same schema repeatedly.
  private readonly validators = new Map<string, ValidateFunction>();

  constructor(private readonly toolRegistry: ToolRegistryService) {}

  /**
   * Executes a registered tool after validating its JSON arguments.
   */
  async execute(toolName: string, rawArguments: string): Promise<unknown> {
    // Resolve the requested tool from the trusted registry.
    const tool = this.toolRegistry.get(toolName);

    if (!tool) {
      throw new NotFoundException(`Tool "${toolName}" is not registered.`);
    }

    // Parse the JSON arguments returned by the AI model.
    let parsedArguments: unknown;

    try {
      parsedArguments = JSON.parse(rawArguments);
    } catch {
      throw new BadRequestException('The tool arguments must be valid JSON.');
    }

    // Tool arguments must be a JSON object.
    if (
      parsedArguments === null ||
      typeof parsedArguments !== 'object' ||
      Array.isArray(parsedArguments)
    ) {
      throw new BadRequestException(
        'The tool arguments must be a JSON object.',
      );
    }

    // Reuse the compiled validator when this tool is executed again.
    let validate = this.validators.get(toolName);

    if (!validate) {
      try {
        validate = this.ajv.compile(tool.parameters);
        this.validators.set(toolName, validate);
      } catch (error) {
        this.logger.error(
          `Failed to compile the JSON Schema for tool "${toolName}".`,
          error instanceof Error ? error.stack : undefined,
        );

        throw new InternalServerErrorException(
          'The registered tool has an invalid JSON Schema.',
        );
      }
    }

    // Reject arguments that do not match the tool's JSON Schema.
    if (!validate(parsedArguments)) {
      const validationErrors = (validate.errors ?? [])
        .map((error) => {
          const path = error.instancePath || '/';

          return `${path} ${error.message ?? 'is invalid'}`;
        })
        .join('; ');

      throw new BadRequestException({
        message: 'The tool arguments are invalid.',
        errors: validationErrors,
      });
    }

    let timeout: ReturnType<typeof setTimeout> | undefined;

    try {
      // Enforce a maximum execution time for registered tools.
      const executionPromise = tool.execute(parsedArguments);

      const timeoutPromise = new Promise<never>((_, reject) => {
        timeout = setTimeout(() => {
          reject(
            new RequestTimeoutException(
              `Tool "${toolName}" exceeded its execution time limit.`,
            ),
          );
        }, this.TOOL_EXECUTION_TIMEOUT_MS);
      });

      const result = await Promise.race([executionPromise, timeoutPromise]);

      // Ensure the tool output can be safely serialized as JSON.
      let serializedResult: string | undefined;

      try {
        serializedResult = JSON.stringify(result);
      } catch {
        throw new InternalServerErrorException(
          'The tool returned an invalid output.',
        );
      }

      if (serializedResult === undefined) {
        throw new InternalServerErrorException(
          'The tool returned an unsupported output.',
        );
      }

      // Prevent oversized tool results from entering the AI conversation.
      const outputSize = Buffer.byteLength(serializedResult, 'utf8');

      if (outputSize > this.MAX_TOOL_OUTPUT_BYTES) {
        this.logger.warn(
          `Tool "${toolName}" exceeded the maximum output size: ${outputSize} bytes.`,
        );

        throw new InternalServerErrorException(
          'The tool output exceeded the allowed size.',
        );
      }

      return result;
    } catch (error) {
      // Preserve intentional errors generated by the executor.
      if (
        error instanceof RequestTimeoutException ||
        error instanceof InternalServerErrorException
      ) {
        if (error instanceof RequestTimeoutException) {
          this.logger.warn(
            `Execution timed out for support tool "${toolName}".`,
          );
        }

        throw error;
      }

      // Log internal details without exposing them to the API consumer.
      this.logger.error(
        `Execution failed for support tool "${toolName}".`,
        error instanceof Error ? error.stack : undefined,
      );

      throw new InternalServerErrorException(
        'The requested support tool could not be executed.',
      );
    } finally {
      // Always clear the timeout to avoid unnecessary timer execution.
      if (timeout) {
        clearTimeout(timeout);
      }
    }
  }
}
